  function loadSeen() {
    try { return JSON.parse(localStorage.getItem(SEEN_KEY) || '{}'); } catch (e) { return {}; }
  }
  function saveSeen(obj) {
    try { localStorage.setItem(SEEN_KEY, JSON.stringify(obj)); } catch (e) {}
  }

  window.OliveQuizBank = {
    getTotalCount: function () {
      return POOL_SIZE * 3; // 10,800 سؤال فريد!
    },
    getRoundQuestions: function (level, count, customAdminQuestions) {
      const lvl = (level === 'hard' || level === 'medium') ? level : 'easy';
      const need = Math.max(1, Math.min(30, Number(count) || 5));
      const seenMap = loadSeen();
      let seenArr = Array.isArray(seenMap[lvl]) ? seenMap[lvl] : [];
      if (seenArr.length > POOL_SIZE - need - 20) seenArr = []; // إعادة ضبط بعد آلاف الأسئلة
      const seenSet = new Set(seenArr);

      const picked = [];
      const usedTextSet = new Set();

      // إدراج أسئلة المدير المخصصة أولاً (إن لم تُعرض في نفس الجلسة)
      if (Array.isArray(customAdminQuestions) && customAdminQuestions.length > 0) {
        const shuffledAdmin = customAdminQuestions.slice().sort(() => Math.random() - 0.5);
        for (const cq of shuffledAdmin) {
          if (picked.length >= Math.min(2, need)) break;
          if (cq && cq.q && !usedTextSet.has(cq.q)) {
            const cId = 'adm_' + cq.q.slice(0, 24);
            if (!seenSet.has(cId)) {
              picked.push({ id: cId, q: cq.q, options: cq.options, correct: Number(cq.correct) || 0, fact: cq.fact || '' });
              usedTextSet.add(cq.q);
              seenSet.add(cId);
            }
          }
        }
      }

      // اختيار عشوائي من الأسئلة المحررة والمولدة بدون أي تكرار في الجولة أو الجولات السابقة
      let attempts = 0;
      const curatedLen = (CURATED[lvl] || []).length;
      while (picked.length < need && attempts < 200) {
        attempts++;
        // 40% فرصة للأسئلة المحررة يدوياً غير المرئية و60% من البنك الواسع 3600
        let idx;
        if (attempts < 40 && Math.random() < 0.45) {
          idx = Math.floor(Math.random() * curatedLen);
        } else {
          idx = Math.floor(Math.random() * POOL_SIZE);
        }
        const qObj = generateByIndex(lvl, idx);
        if (!seenSet.has(qObj.id) && !usedTextSet.has(qObj.q)) {
          picked.push(qObj);
          seenSet.add(qObj.id);
          usedTextSet.add(qObj.q);
        }
      }

      // حفظ آخر 800 سؤال مرئي لكل مستوى لضمان التجدد الدائم مع بقاء localStorage خفيفاً جداً
      seenMap[lvl] = Array.from(seenSet).slice(-800);
      saveSeen(seenMap);
      return picked;
    }
  };
